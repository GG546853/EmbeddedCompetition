#include "Printer_task.h"
#include "PRINTER.h"
#include "usart.h"

#define huart_printer huart7

osThreadId_t Printer_TaskHandle;
const osThreadAttr_t PrinterTask_attributes = {
  .name = "PrinterTask",
  .priority = (osPriority_t) osPriorityNormal + 1,
  .stack_size = 512 * 4
};

void Print_Recent_BOM(void);


void Printer_Task(void *argument)
{
	Print_Recent_BOM();
	while(1)
	{

		vTaskDelay(pdMS_TO_TICKS(10));
	}
}

